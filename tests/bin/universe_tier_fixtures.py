#!/usr/bin/env python3
"""The fixture entries that make the non-default `instance_tier`s testable.

`tests/data/uniprot_universe.dat.gz` is otherwise 100 % human and 100 % `Reviewed;`,
so strata 1-3 of ppi-splitting's tier ladder (`other_reviewed`,
`human_unreviewed`, `other_unreviewed`) cannot fill from it and every test of a
widened protein universe would pass vacuously. These three entries fill one
stratum each, with a matching row in `tests/data/pfam/Pfam-A.regions.tsv.gz` so
FETCH_DOMAIN_META can actually sample them.

**The default `-profile test` run is unchanged by them.** It runs
`--instance_tier human_reviewed`, which derives `swissprot_taxon_ids = 9606` (so
PARSE_SWISSPROT drops both mouse entries) and the `human_reviewed` stratum only
(so the human TrEMBL entry is parsed but never sampled). They cost the default
run one extra FASTA record and nothing else.

Kept in its own module, and appended rather than woven into
`write_enrich_fixtures()`, for the same reason `Pfam-A.regions.tsv.gz` is not
regenerated by `make_test_fixtures.py`: the 85-family fixture is tuned against
`SAMPLE_NEGATIVES_ILP`'s candidate coverage (see conf/test.config), and a full
regeneration has to be re-verified against that. Appending is idempotent and
touches nothing else.

Run standalone to (re)apply to the committed fixtures::

    tests/bin/universe_tier_fixtures.py --data tests/data
"""

import argparse
import gzip
import os

#: One entry per stratum that the base fixture cannot fill. `family` must be a
#: family the base `Pfam-A.regions.tsv.gz` already carries -- an unknown one would
#: never be requested by EXPORT_UNION_FAMILIES and the entry would go unused.
#:
#: Accessions follow UniProt's `[A-NR-Z][0-9][A-Z][A-Z0-9]{2}[0-9]` shape so
#: nothing that pattern-matches them rejects the file, while `TIE` keeps them
#: obviously synthetic.
EXTRA_ENTRIES = (
    {
        "acc": "X0TIE2",
        "entry_name": "TIER2_HUMAN",
        "taxid": "9606",
        "reviewed": False,
        "organism": "Homo sapiens (Human)",
        "family": "PF00001",
        "stratum": "human_unreviewed",
    },
    {
        "acc": "X0TIE1",
        "entry_name": "TIER1_MOUSE",
        "taxid": "10090",
        "reviewed": True,
        "organism": "Mus musculus (Mouse)",
        "family": "PF00179",
        "stratum": "other_reviewed",
    },
    {
        "acc": "X0TIE3",
        "entry_name": "TIER3_MOUSE",
        "taxid": "10090",
        "reviewed": False,
        "organism": "Mus musculus (Mouse)",
        "family": "PF00595",
        "stratum": "other_unreviewed",
    },
)

#: Where the single Pfam region sits in the synthetic parent sequence. One shape
#: for all three: the region has to lie inside the sequence, which is the only
#: invariant `Pfam-A.regions.tsv.gz` and the flat file share.
DOMAIN_START = 21
DOMAIN_END = 80
SEQ_LENGTH = 120

REGION_COLUMNS = [
    "pfamseq_acc", "seq_version", "crc64", "md5",
    "pfamA_acc", "seq_start", "seq_end", "ali_start", "ali_end",
]


#: Real residues only. The domain sequence of a sampled instance is what the
#: embedding models are handed, and a digit or an X in it is not an amino acid --
#: so the distinguishing motif is a rotation of this alphabet, not the accession.
AMINO_ACIDS = "ACDEFGHIKLMNPQRSTVWY"


def sequence_for(entry):
    """A deterministic parent sequence with a distinguishable domain window.

    Poly-A outside the domain, a per-entry rotation of the amino-acid alphabet
    inside it, so a mis-sliced region is visible by eye in a failing test rather
    than being 120 identical residues.
    """
    offset = EXTRA_ENTRIES.index(entry)
    motif = AMINO_ACIDS[offset:] + AMINO_ACIDS[:offset]
    span = DOMAIN_END - DOMAIN_START + 1
    return (
        "A" * (DOMAIN_START - 1)
        + (motif * span)[:span]
        + "A" * (SEQ_LENGTH - DOMAIN_END)
    )


def dat_entry(entry):
    """One UniProt flat-file entry, in the subset `parse_swissprot_dat.py` reads."""
    seq = sequence_for(entry)
    review = "Reviewed;" if entry["reviewed"] else "Unreviewed;"
    lines = [
        f"ID   {entry['entry_name']}   {review}   {len(seq)} AA.",
        f"AC   {entry['acc']};",
        f"DE   RecName: Full=Synthetic {entry['stratum']} fixture protein {entry['acc']};",
        f"GN   Name={entry['entry_name'].split('_')[0].lower()};",
        f"OS   {entry['organism']}.",
        f"OX   NCBI_TaxID={entry['taxid']};",
        "DR   GO; GO:0005515; F:protein binding; IEA:fixture.",
        f"DR   Pfam; {entry['family']}; {entry['family']}_name; 1.",
    ]
    # Only reviewed entries get a STRING cross-reference, which is what UniProt
    # itself does -- measured on uniprot_trembl_human.dat.gz, 4,616 entries carried
    # 15 `DR STRING;` lines. FETCH_STRING_LINKS reports that gap, so the fixture
    # has to reproduce it.
    if entry["reviewed"]:
        lines.append(f"DR   STRING; {entry['taxid']}.ENSFIXTURE{entry['acc'][-1]}; -.")
    lines.append(f"SQ   SEQUENCE   {len(seq)} AA;  0 MW;  0000000000000000 CRC64;")
    lines += ["     " + seq[i:i + 60] for i in range(0, len(seq), 60)]
    lines.append("//")
    return "\n".join(lines) + "\n"


def region_row(entry):
    return "\t".join([
        entry["acc"], "1", "0" * 16, "0" * 32, entry["family"],
        str(DOMAIN_START), str(DOMAIN_END), str(DOMAIN_START), str(DOMAIN_END),
    ]) + "\n"


def _append_gz(path, text, marker):
    """Append `text` to a gzipped text file unless `marker` is already in it."""
    with gzip.open(path, "rt", encoding="latin-1") as fh:
        existing = fh.read()
    if marker in existing:
        return False
    with gzip.open(path, "wt", encoding="latin-1") as fh:
        fh.write(existing)
        fh.write(text)
    return True


def apply(data_dir):
    """Append the entries to the committed fixtures. Idempotent; returns a log."""
    dat = os.path.join(data_dir, "uniprot_universe.dat.gz")
    regions = os.path.join(data_dir, "pfam", "Pfam-A.regions.tsv.gz")
    messages = []

    marker = EXTRA_ENTRIES[0]["acc"]
    if _append_gz(dat, "".join(dat_entry(e) for e in EXTRA_ENTRIES), marker):
        messages.append(f"appended {len(EXTRA_ENTRIES)} tier entries to {dat}")
    else:
        messages.append(f"{dat} already carries them")

    if _append_gz(regions, "".join(region_row(e) for e in EXTRA_ENTRIES), marker):
        messages.append(f"appended {len(EXTRA_ENTRIES)} regions to {regions}")
    else:
        messages.append(f"{regions} already carries them")
    return messages


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", default="tests/data", help="fixture directory")
    args = p.parse_args()
    for message in apply(args.data):
        print(message)


if __name__ == "__main__":
    main()
